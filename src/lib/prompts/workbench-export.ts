/**
 * Renders docs/workbench/ — an exact mirror of what the app sends to Claude —
 * plus src/lib/prompts/version.gen.ts. Generated, never hand-edited:
 * `bun run prompts:export` writes, `bun run prompts:check` verifies.
 */
import { createHash } from "node:crypto";
import { EMPTY_INPUT, type ListingInput } from "../listing-types";
import { VOICE_PROMPTS, VOICES } from "../voices";
import { bannedReminder, pleaseNoteReminder } from "../output-guards";
import {
  CALL_SETTINGS,
  CORE_SCHEMA,
  CORE_TOOL,
  DEFAULT_CLAUDE_MODEL,
  EXTRACT_TOOL,
  MARKETING_SCHEMA,
  MARKETING_TOOL,
  RETRY_RULES,
  TOOL_DESCRIPTIONS,
  buildExtractSchema,
} from "./calls";
import {
  CORE_USER_TEMPLATE,
  EXTRACT_SYSTEM,
  EXTRACT_USER_TEMPLATE,
  LIMIT_REMINDER,
  MARKETING_REMINDER,
  MARKETING_USER_TEMPLATE,
  SYSTEM_TEMPLATE,
} from "./templates";
import { VARIABLE_SOURCES, normaliseInput, promptVars, type PromptVarName } from "./render";
import {
  GRADER_SCHEMA,
  GRADER_SETTINGS,
  GRADER_SYSTEM,
  GRADER_TOOL,
  GRADER_USER_TEMPLATE,
} from "./grader";

export interface ExportCase {
  id: string;
  call: "pack" | "extract";
  tags?: string[];
  input?: Partial<ListingInput>;
  notes?: string;
}

const W = "docs/workbench";
const VAR_COLUMNS: (PromptVarName | "NOTES")[] = [
  "BRAND_VOICE",
  "PROPERTY_DETAILS",
  "MATERIAL_INFORMATION",
  "PRIVATE_NOTES",
  "VOICE_NOTES",
  "SELLER_APPROVAL",
  "GAP_QUESTIONS",
  "LIMIT_REMINDER",
  "NOTES",
];

const json = (v: unknown) => JSON.stringify(v, null, 2) + "\n";
const tool = (name: string, description: string, schema: unknown) =>
  json({ name, description, input_schema: schema });

function csvCell(v: string): string {
  return /[",\n\r]/.test(v) ? `"${v.replace(/"/g, '""')}"` : v;
}

/** Merge a case over EMPTY_INPUT and normalise it exactly like the app does. */
export function caseInput(c: ExportCase): ListingInput {
  return normaliseInput({ ...EMPTY_INPUT, ...(c.input ?? {}) } as ListingInput);
}

function caseRow(c: ExportCase): Record<string, string> {
  const row: Record<string, string> = { id: c.id, call: c.call, tags: (c.tags ?? []).join(" ") };
  for (const k of VAR_COLUMNS) row[k] = "";
  if (c.call === "pack") Object.assign(row, promptVars(caseInput(c)));
  else row.NOTES = (c.notes ?? "").trim();
  return row;
}

function settingsJson(): string {
  return json({
    model: DEFAULT_CLAUDE_MODEL,
    modelNote:
      "Production reads the model id from app_settings.claude_model (Admin page) and falls back to this default. Use the same model as production when comparing.",
    anthropicVersion: "2023-06-01",
    calls: {
      core: {
        tool: CORE_TOOL,
        tool_choice: { type: "tool", name: CORE_TOOL },
        max_tokens: CALL_SETTINGS.core.maxTokens,
        retry_max_tokens: CALL_SETTINGS.core.retryMaxTokens,
        temperature: CALL_SETTINGS.core.temperature ?? "not sent (API default 1.0)",
        timeout_ms: CALL_SETTINGS.core.timeoutMs,
        system: "system.txt",
        user: "core.user.txt",
        retries: RETRY_RULES.core,
      },
      marketing: {
        tool: MARKETING_TOOL,
        tool_choice: { type: "tool", name: MARKETING_TOOL },
        max_tokens: CALL_SETTINGS.marketing.maxTokens,
        temperature: CALL_SETTINGS.marketing.temperature ?? "not sent (API default 1.0)",
        timeout_ms: CALL_SETTINGS.marketing.timeoutMs,
        system: "system.txt",
        user: "marketing.user.txt",
        retries: RETRY_RULES.marketing,
      },
      extract: {
        tool: EXTRACT_TOOL,
        tool_choice: { type: "tool", name: EXTRACT_TOOL },
        max_tokens: CALL_SETTINGS.extract.maxTokens,
        temperature: CALL_SETTINGS.extract.temperature,
        timeout_ms: CALL_SETTINGS.extract.timeoutMs,
        system: "extract.system.txt",
        user: "extract.user.txt",
        retries: RETRY_RULES.extract,
      },
    },
    postProcessing: {
      core: "validateCoreOutput() in src/lib/listing-types.ts",
      marketing:
        "validateMarketingOutput() in src/lib/listing-types.ts; the seller email subject is set by the app",
      extract:
        "filterExtraction() in src/lib/extract-filter.ts (drops fields without a verbatim quote)",
    },
  });
}

function readme(version: string): string {
  const vars = VAR_COLUMNS.map((k) => `| \`{{${k}}}\` | ${VARIABLE_SOURCES[k]} |`).join("\n");
  const voices = VOICES.map((v) => `\`voices/${v.id}.txt\` (${v.name})`).join(", ");
  return `<!-- GENERATED by \`bun run prompts:export\` — do not edit by hand. -->
# Quill prompts in Claude Workbench

Everything in this folder is generated from the code the app runs, so what you
test here is exactly what Quill sends. Prompt version: \`${version}\` (also in \`VERSION\`).

Quill makes **three** Claude calls. Each one is a separate Workbench prompt:

| Call | When | System | User | Tool |
| --- | --- | --- | --- | --- |
| Core | Generate (listing, strapline, key features, headline) | \`system.txt\` | \`core.user.txt\` | \`tools/core.json\` |
| Marketing | Generate, in parallel with Core (Email Blast, seller email, social) | \`system.txt\` | \`marketing.user.txt\` | \`tools/marketing.json\` |
| Extract | "Fill the form from these notes" | \`extract.system.txt\` | \`extract.user.txt\` | \`tools/extract.json\` |

## Set up one call (repeat for each)

1. Go to **console.anthropic.com → Workbench** and create a new prompt. Name it after the call (e.g. "Quill – Core").
2. **System prompt**: open the System file from the table above, copy everything and paste it into the **System** box.
3. **User message**: open the User file, copy everything and paste it into the first **User** message.
4. **Tool**: click **Add tool** (or "Tools" → "+"), and paste the matching file from \`tools/\`. It contains the tool name, description and input schema.
5. **Tool choice**: set it to **Specific tool** and pick the tool you just added (\`${CORE_TOOL}\`, \`${MARKETING_TOOL}\` or \`${EXTRACT_TOOL}\`).
6. **Model settings** (the settings icon): set the model, **Temperature** and **Max tokens** from \`settings.json\` for that call.
   Use the temperature shown in \`settings.json\` for each call ("not sent" means the Workbench default, 1.0). Extract uses 0.
7. **Variables**: anything in double curly brackets, like \`{{BRAND_VOICE}}\`, is a variable. Workbench detects them and shows a box for each one.
   Fill them by hand, or go to **Evaluate → Import test cases** and choose \`test-cases.csv\`. Each row is one test case with every variable already filled in exactly as the app would.
   The CSV has a column for every variable of all three calls; rows for Extract only fill \`NOTES\`, and rows for Core/Marketing fill the rest.
   For Core, leave \`{{LIMIT_REMINDER}}\` empty (the app only fills it with \`core.limit-reminder.txt\` on a retry).
8. Click **Run**. The answer appears as a tool call with JSON input.

**Brand voice:** \`{{BRAND_VOICE}}\` in the System prompt is one of ${voices}. Paste the voice you want to test.

## What Workbench shows vs what agents see

Workbench shows Claude's **raw** tool output. The app then tidies it before an agent sees it:
Core goes through \`validateCoreOutput\`, Marketing through \`validateMarketingOutput\` (the seller email subject line is added by the app),
and Extract through \`filterExtraction\` (any field whose evidence quote isn't in the notes is dropped).
The app also retries on certain failures — see \`retries\` in \`settings.json\`.

## Variables

| Variable | Filled by (src/lib/prompts/render.ts) |
| --- | --- |
${vars}

## Files

- \`system.txt\` — master prompt + brand-voice slot (Core and Marketing)
- \`voices/*.txt\` — the five brand voices
- \`core.user.txt\`, \`core.limit-reminder.txt\`, \`marketing.user.txt\`, \`marketing.reminder.txt\` — user templates (reminders are only added on a retry)
- \`extract.system.txt\`, \`extract.user.txt\` — "Fill the form" call
- \`tools/*.json\` — tool definitions; \`settings.json\` — model, max tokens, temperature, tool choice, timeouts and retries
- \`test-cases.csv\` / \`test-cases.json\` — every eval case with all variables rendered
- \`grader/\` — the optional LLM grader used by \`bun run evals -- --llm-grade\` (system, user template, tool)
- \`VERSION\` — sha256 of the prompt files (stamped on every new listing as \`output.meta.promptVersion\`)

## For developers

- Change prompts in \`src/lib/prompts/*\`, \`master-listing-prompt.ts\`, \`voices.ts\`, \`listing-fields.ts\`, \`material-info.ts\` or \`fact-check.ts\`, then run \`bun run prompts:export\` and \`bun run test\`.
- \`bun run evals -- --label <name> [--llm-grade]\` runs the eval harness; reports land in \`docs/evals/\`.
- Admins can copy the exact request for any form or saved listing from the **Copy for Workbench** menu in the app.
`;
}

/** Every generated file, keyed by repo-relative path. */
export function renderWorkbenchFiles(cases: ExportCase[]): Record<string, string> {
  const prompt: Record<string, string> = {
    [`${W}/system.txt`]: SYSTEM_TEMPLATE,
    [`${W}/core.user.txt`]: CORE_USER_TEMPLATE,
    [`${W}/core.limit-reminder.txt`]: LIMIT_REMINDER,
    [`${W}/marketing.user.txt`]: MARKETING_USER_TEMPLATE,
    [`${W}/marketing.reminder.txt`]: MARKETING_REMINDER,
    [`${W}/banned-reminder.txt`]: bannedReminder(["<phrase>", "<phrase>"]),
    [`${W}/please-note-reminder.txt`]: pleaseNoteReminder(["<where>"]),
    [`${W}/extract.system.txt`]: EXTRACT_SYSTEM,
    [`${W}/extract.user.txt`]: EXTRACT_USER_TEMPLATE,
    [`${W}/tools/core.json`]: tool(CORE_TOOL, TOOL_DESCRIPTIONS.core, CORE_SCHEMA),
    [`${W}/tools/marketing.json`]: tool(
      MARKETING_TOOL,
      TOOL_DESCRIPTIONS.marketing,
      MARKETING_SCHEMA,
    ),
    [`${W}/tools/extract.json`]: tool(
      EXTRACT_TOOL,
      TOOL_DESCRIPTIONS.extract,
      buildExtractSchema(),
    ),
    [`${W}/settings.json`]: settingsJson(),
  };
  for (const v of VOICES) prompt[`${W}/voices/${v.id}.txt`] = VOICE_PROMPTS[v.id];

  const h = createHash("sha256");
  for (const k of Object.keys(prompt).sort()) h.update(`${k}\0${prompt[k]}\0`);
  const version = h.digest("hex").slice(0, 12);

  const rows = cases.map(caseRow);
  const header = ["id", "call", "tags", ...VAR_COLUMNS];
  const csv =
    [header.join(","), ...rows.map((r) => header.map((k) => csvCell(r[k] ?? "")).join(","))].join(
      "\n",
    ) + "\n";

  return {
    ...prompt,
    [`${W}/test-cases.csv`]: csv,
    [`${W}/test-cases.json`]: json(rows),
    [`${W}/grader/system.txt`]: GRADER_SYSTEM,
    [`${W}/grader/user.txt`]: GRADER_USER_TEMPLATE,
    [`${W}/grader/tool.json`]: json({
      name: GRADER_TOOL,
      description: "Submit the scores, verdict and fixes.",
      input_schema: GRADER_SCHEMA,
      settings: GRADER_SETTINGS,
    }),
    [`${W}/VERSION`]: version + "\n",
    [`${W}/README.md`]: readme(version),
    "docs/claude-workbench-master-prompt.md": `<!-- GENERATED by \`bun run prompts:export\` — do not edit by hand. -->
# Quill — Claude Workbench kit

The Workbench kit moved to [docs/workbench/README.md](workbench/README.md). It contains the
exact system prompt, brand voices, user templates, tool schemas, settings and test cases for all
three calls (core, marketing, extract), generated from the app's code. Prompt version \`${version}\`.
`,
    "src/lib/prompts/version.gen.ts": `// GENERATED by \`bun run prompts:export\` — do not edit by hand.\n/** sha256 (first 12 hex) of the Workbench prompt files. */\nexport const PROMPT_VERSION = "${version}";\n`,
  };
}
